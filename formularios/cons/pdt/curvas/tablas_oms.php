    public static function getPercentiles($tipo, $sexo, $edad_meses) {
        // Determinar tabla según tipo y sexo
        switch($tipo) {
            case 'talla':
                $tabla = self::$tablas_talla[$sexo] ?? self::$tablas_talla['F'];
                break;
            case 'peso':
                $tabla = self::$tablas_peso[$sexo] ?? self::$tablas_peso['F'];
                break;
            case 'circ_cefalica':
                $tabla = self::$tablas_circ_cefalica[$sexo] ?? self::$tablas_circ_cefalica['F'];
                break;
            default:
                return null;
        }
        
        // Encontrar puntos más cercanos para interpolación
        $prev = null;
        $next = null;
        
        foreach ($tabla as $punto) {
            if ($punto[0] <= $edad_meses) {
                $prev = $punto;
            } else {
                $next = $punto;
                break;
            }
        }
        
        // Si no hay siguiente punto, usar el último
        if (!$next && $prev) {
            $next = $prev;
        }
        
        // Interpolar linealmente
        if ($prev && $next && $prev[0] != $next[0]) {
            $t = ($edad_meses - $prev[0]) / ($next[0] - $prev[0]);
            
            return [
                'P3' => $prev[1] + ($next[1] - $prev[1]) * $t,
                'P15' => $prev[2] + ($next[2] - $prev[2]) * $t,
                'P50' => $prev[3] + ($next[3] - $prev[3]) * $t,
                'P85' => $prev[4] + ($next[4] - $prev[4]) * $t,
                'P97' => $prev[5] + ($next[5] - $prev[5]) * $t
            ];
        } elseif ($prev) {
            // Si edades coinciden exactamente
            return [
                'P3' => $prev[1],
                'P15' => $prev[2],
                'P50' => $prev[3],
                'P85' => $prev[4],
                'P97' => $prev[5]
            ];
        }
        
        return null;
    }
    
    public static function getZScore($valor, $percentiles) {
        if (!$percentiles) return null;
        
        // Cálculo aproximado de Z-score basado en percentiles
        $p50 = $percentiles['P50'];
        $sd = ($percentiles['P85'] - $p50) / 1.036; // Aproximación SD
        
        if ($sd > 0) {
            return ($valor - $p50) / $sd;
        }
        
        return null;
    }
    
    public static function getPercentilValor($valor, $percentiles) {
        if (!$percentiles) return 'N/A';
        
        // Determinar percentil aproximado
        if ($valor <= $percentiles['P3']) return '< P3';
        if ($valor <= $percentiles['P15']) return 'P3-P15';
        if ($valor <= $percentiles['P50']) return 'P15-P50';
        if ($valor <= $percentiles['P85']) return 'P50-P85';
        if ($valor <= $percentiles['P97']) return 'P85-P97';
        return '> P97';
    }
