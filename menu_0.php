<script>
function actualizarClienteActivo(clienteId) {
  const formData = new FormData();
  formData.append('id', clienteId);
  fetch('formularios/cli/seleccionar_cliente.php', {
    method: 'POST',
    body: formData
  })
  .then(res => res.json())
  .then(data => {
	document.getElementById('Clienteactivo').textContent = data.nombre;
  });
}
</script>


<script>
	class NotificadorLaboratorio {
		constructor() {
			this.container = $('#notificacionesContainer');
			this.ultimaVerificacion = null;
			this.inicializar();
		}
		
		inicializar() {
			// Verificar cada 20 segundos
			setInterval(() => this.verificarNuevasOrdenes(), 20000);
			
			// Verificar inmediatamente al cargar la página
			this.verificarNuevasOrdenes();
		}
		
		verificarNuevasOrdenes() {
			$.getJSON(FORM_URL+'lab/obtener_notificaciones_lab.php', (data) => {
				if (data.success && data.notificaciones.length > 0) {
					data.notificaciones.forEach(notif => {
						this.mostrarNotificacionOrden(notif);
					});
				}
			});
		}
		
		mostrarNotificacionOrden(notificacion) {
			const toastHTML = `
			<div class="toast" role="alert">
				<div class="toast-header bg-primary text-white">
					<i class="bi bi-bell-fill me-2"></i>
					<strong class="me-auto">${notificacion.titulo}</strong>
					<small>Ahora</small>
					<button type="button" class="btn-close btn-close-white" data-bs-dismiss="toast"></button>
				</div>
				<div class="toast-body">
					<p class="mb-1">${notificacion.mensaje}</p>
					<div class="mt-2 pt-2 border-top">
						<a href="ver_orden.php?id=${notificacion.id_orden}" 
						   class="btn btn-sm btn-success">Ver Orden</a>
						<button class="btn btn-sm btn-secondary" data-bs-dismiss="toast">
							Cerrar
						</button>
					</div>
				</div>
			</div>`;
			
			this.container.append(toastHTML);
			$('.toast').toast('show');
			
			// Auto-cerrar después de 10 segundos
			setTimeout(() => {
				$('.toast').toast('hide');
			}, 10000);
		}
	}

	// Inicializar solo si el usuario es de laboratorio
